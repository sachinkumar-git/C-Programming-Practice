#include<stdio.h>
int main(){
    // increment operator
    // ++i (pre increment)
    // i++ (post increment)

    int i = 1;
    printf("%d \n", i++); // use, then increase → 1 then 2 
    printf("%d \n", i);

    int n = 1;
    printf("%d \n", ++n); //  increase , then use
    printf("%d \n", n);



    return 0;
}