// all types of relational operators


#include<stdio.h>
#include<math.h>

int main(){

    // equal to 

    printf("%d \n", 4 == 4);
    printf("%d \n", 4 == 3);

    // greater than , greater than equal to
    printf("%d \n", 4 > 3);  
    printf("%d \n", 3 > 4);
    printf("%d \n", 4 > 4);
    printf("%d \n", 4 >= 4);

    // less than , less than equal to
    printf("%d \n", 3 <= 3);
    printf("%d \n", 4 < 3);  
    printf("%d \n", 3 <= 4);

    // not equal to 
    printf("%d \n", 4 != 4);
    printf("%d \n", 4 == 3);

    return 0;
}
